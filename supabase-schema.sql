-- CS2 Vault starter schema for Supabase (PostgreSQL)
-- Run only after creating a Supabase project and reviewing the policies.

create table if not exists public.profiles (
  id uuid primary key references auth.users(id) on delete cascade,
  display_name text not null default 'Player' check (char_length(display_name) between 1 and 24),
  bio text not null default '' check (char_length(bio) <= 160),
  xp integer not null default 0 check (xp >= 0),
  created_at timestamptz not null default now()
);

create table if not exists public.collections (
  id bigint generated by default as identity primary key,
  name text not null unique,
  category text not null check (category in ('knife','weapon','theme','glove')),
  description text not null default '',
  symbol text not null default '◆',
  art_theme text not null default 'onyx',
  created_at timestamptz not null default now()
);

create table if not exists public.skins (
  id bigint generated by default as identity primary key,
  name text not null,
  weapon text not null,
  rarity text not null check (rarity in ('Consumer','Industrial','Mil-Spec','Restricted','Classified','Covert','Contraband')),
  image_url text,
  wear text,
  stattrak boolean not null default false,
  created_at timestamptz not null default now()
);

create table if not exists public.collection_skins (
  collection_id bigint not null references public.collections(id) on delete cascade,
  skin_id bigint not null references public.skins(id) on delete cascade,
  primary key (collection_id, skin_id)
);

create table if not exists public.inventory_items (
  user_id uuid not null references auth.users(id) on delete cascade,
  skin_id bigint not null references public.skins(id) on delete cascade,
  added_at timestamptz not null default now(),
  is_favorite boolean not null default false,
  primary key (user_id, skin_id)
);

create table if not exists public.challenge_completions (
  user_id uuid not null references auth.users(id) on delete cascade,
  challenge_key text not null,
  completed_at timestamptz not null default now(),
  primary key (user_id, challenge_key)
);

alter table public.profiles enable row level security;
alter table public.collections enable row level security;
alter table public.skins enable row level security;
alter table public.collection_skins enable row level security;
alter table public.inventory_items enable row level security;
alter table public.challenge_completions enable row level security;

-- Public read access for catalogue content.
create policy "Catalogue is viewable by everyone" on public.collections
for select using (true);
create policy "Skins are viewable by everyone" on public.skins
for select using (true);
create policy "Collection links are viewable by everyone" on public.collection_skins
for select using (true);

-- Profiles are publicly readable, but only owners may update their own profile.
create policy "Profiles are viewable by everyone" on public.profiles
for select using (true);
create policy "Users can insert their own profile" on public.profiles
for insert with check (auth.uid() = id);
create policy "Users can update their own profile" on public.profiles
for update using (auth.uid() = id) with check (auth.uid() = id);

-- Inventory and challenge records are private to their owner.
create policy "Users can view their own inventory" on public.inventory_items
for select using (auth.uid() = user_id);
create policy "Users can add their own inventory items" on public.inventory_items
for insert with check (auth.uid() = user_id);
create policy "Users can update their own inventory items" on public.inventory_items
for update using (auth.uid() = user_id) with check (auth.uid() = user_id);
create policy "Users can remove their own inventory items" on public.inventory_items
for delete using (auth.uid() = user_id);

create policy "Users can view their own challenge completions" on public.challenge_completions
for select using (auth.uid() = user_id);
create policy "Users can complete their own challenges" on public.challenge_completions
for insert with check (auth.uid() = user_id);
